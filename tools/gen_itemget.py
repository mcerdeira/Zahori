"""Genera los sprites del "objeto obtenido" (paleta gameboy-color-type1) en sprites/.

- player_itemget_spr_0: el player (16x16, mismo estilo que player_idle) con los brazos
  en alto, como sosteniendo algo sobre la cabeza.
- rod_spr_0..1: la vara zahorí suelta (16x16, horquilla en Y, mismos colores de madera que
  la de la hermana) con un destello que va cambiando de lugar. Se muestra sobre la cabeza
  del player cuando la agarra.

Uso: python3 tools/gen_itemget.py
"""
from pathlib import Path

from PIL import Image

OUT = Path(__file__).resolve().parent.parent / "sprites"


def C(*a):
    return a + (255,)


A = C(227, 230, 255)  # piel/cabeza (igual que el player)
B = C(0, 0, 0)
R = C(230, 0, 0)  # túnica
W1 = C(131, 49, 0)  # madera oscura
W2 = C(165, 107, 49)
W3 = C(255, 173, 99)
SPARK = C(255, 255, 255)
GLOW = C(255, 255, 165)

# Player con los brazos en alto: misma cabeza, túnica y piernas que player_idle_spr_0,
# los brazos salen de los hombros en diagonal y suben al costado de la cabeza.
PLAYER = """
................
..A.........A...
..A..AAAAA..A...
..A.AAAAAAA.A...
..A.AAABABA.A...
..A.AAAAAAA.A...
...A.AAAAA.A....
....ARRRRRA.....
.....RRRRR......
.....RRRRR......
.....RRRRR......
.....RRRRR......
.....AA.AA......
.....AA.AA......
.....AA.AA......
.....AA.AA......
"""

# Vara: horquilla en Y, puntas claras, mango oscuro abajo.
ROD = """
................
...3.......3....
...2.......2....
....2.....2.....
....2.....2.....
.....2...2......
......2.2.......
.......2........
.......2........
.......2........
.......2........
.......1........
.......1........
.......1........
................
................
"""

# Destellos por frame: (x, y) del centro de una crucecita
SPARKS = [(12, 1), (2, 6)]


def from_art(art, colors):
    rows = [r for r in art.strip("\n").split("\n")]
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in colors:
                im.putpixel((x, y), colors[ch])
    return im


def main():
    im = from_art(PLAYER, {"A": A, "B": B, "R": R})
    im.save(OUT / "player_itemget_spr_0.png")
    print("sprites/player_itemget_spr_0.png")
    for i, (sx, sy) in enumerate(SPARKS):
        rod = from_art(ROD, {"1": W1, "2": W2, "3": W3})
        rod.putpixel((sx, sy), SPARK)
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            x, y = sx + dx, sy + dy
            if 0 <= x < 16 and 0 <= y < 16 and rod.getpixel((x, y))[3] == 0:
                rod.putpixel((x, y), GLOW)
        rod.save(OUT / f"rod_spr_{i}.png")
        print(f"sprites/rod_spr_{i}.png")


if __name__ == "__main__":
    main()
